def _aggregate(metric: dict) -> str:
    """SQL of one simple MetricFlow metric (same expression, same aggregation)."""
    agg, expr = metric["agg"], metric["expr"]
    if agg == "sum":
        return f"sum({expr})"
    if agg == "average":
        return f"avg({expr})"
    if agg == "percentile":
        return f"percentile_cont({metric['percentile']}) within group (order by {expr})"
    if agg == "count_distinct":
        return f"count(distinct {expr})"
    raise CatalogueError(f"{metric['name']}: no SQL for agg {agg!r}")


def _metric_sql(row: dict[str, str]) -> str:
    """SQL of a catalogue metric, from the metric dictionaries that also make the YAML."""
    parts = {metric["name"]: metric for metric in build_metrics(row)}
    metric = parts[row["kpi_name"]]
    if metric["type"] == "ratio":
        numerator = _aggregate(parts[metric["numerator"]])
        denominator = _aggregate(parts[metric["denominator"]])
        return f"{numerator}\n        / nullif({denominator}, 0)"
    sql = _aggregate(metric)
    if row["metric_type"] in ("count", "count_distinct"):
        return f"cast({sql} as integer)"
    return sql


def public_rows(rows: list[dict[str, str]]) -> list[dict[str, str]]:
    return [row for row in metric_rows(rows) if row["public_safe"] == "true"]


def build_public_sql(rows: list[dict[str, str]]) -> str:
    check_rules(rows)
    public = public_rows(rows)
    lines = [
        *PUBLIC_SQL_HEADER.splitlines(),
        "",
        "with company_year as (",
        "    select * from {{ ref('sem_company_year') }}",
        "),",
        "",
        "-- every company-year once per kind of group it belongs to",
        "company_groups as (",
    ]
    unions = []
    for group_type, column in GROUP_TYPES.items():
        unions.append(
            "    select\n"
            "        company_year_key,\n"
            "        fiscal_year_label as group_fiscal_year_label,\n"
            f"        '{group_type}' as group_type,\n"
            f"        {column} as group_value\n"
            "    from company_year"
        )
    lines.append("\n    union all\n".join(unions))
    lines += ["),", ""]

    ctes = {}
    for source, spec in MODELS.items():
        cte = spec["view"].removeprefix("sem_")
        ctes[source] = cte
        lines += [
            f"{cte}_rows as (",
            "    select",
            "        company_groups.group_type,",
            "        company_groups.group_value,",
            "        company_groups.group_fiscal_year_label,",
            "        fact.*",
            "    from company_groups",
            f"    inner join {{{{ ref('{spec['view']}') }}}} as fact",
            "        on company_groups.company_year_key = fact.company_year_key",
            "    where company_groups.group_value is not null",
            "),",
            "",
            f"{cte}_metrics as (",
            "    select",
            "        group_type,",
            "        group_value,",
            "        group_fiscal_year_label as fiscal_year_label,",
        ]
        metrics = [row for row in public if row["source_model"] == source]
        for index, row in enumerate(metrics):
            comma = "," if index < len(metrics) - 1 else ""
            lines.append(f"        {_metric_sql(row)} as {row['kpi_name']}{comma}")
        lines += [
            f"    from {cte}_rows",
            "    group by group_type, group_value, group_fiscal_year_label",
            "),",
            "",
        ]

    spine = ctes["fct_company_year"]
    lines += [
        "-- restatements of a year are known only once a later year has been filed",
        "latest as (",
        "    select max(fiscal_year_label) as latest_fiscal_year_label from company_year",
        "),",
        "",
        "-- counts: 0 when the group has no row, empty when the year cannot be observed yet",
        "joined as (",
        "    select",
        f"        {spine}_metrics.group_type,",
        f"        {spine}_metrics.group_value,",
        f"        {spine}_metrics.fiscal_year_label,",
        f"        {spine}_metrics.fiscal_year_label < latest.latest_fiscal_year_label"
        " as has_later_filing,",
    ]
    select_items = []
    for row in public:
        name, cte = row["kpi_name"], ctes[row["source_model"]]
        column = f"{cte}_metrics.{name}"
        if row["metric_type"] in STATISTICS:
            select_items.append(f"        {column}")
        elif row["source_model"] == NEEDS_LATER_FILING:
            select_items.append(
                "        case\n"
                f"            when {spine}_metrics.fiscal_year_label"
                " < latest.latest_fiscal_year_label\n"
                f"                then coalesce({column}, 0)\n"
                f"        end as {name}"
            )
        else:
            select_items.append(f"        coalesce({column}, 0) as {name}")
    lines.append(",\n".join(select_items))
    lines += [f"    from {spine}_metrics", "    cross join latest"]
    for cte in ctes.values():
        if cte == spine:
            continue
        lines += [
            f"    left join {cte}_metrics",
            "        on",
            f"            {spine}_metrics.group_type = {cte}_metrics.group_type",
            f"            and {spine}_metrics.group_value = {cte}_metrics.group_value",
            f"            and {spine}_metrics.fiscal_year_label = {cte}_metrics.fiscal_year_label",
        ]
    lines += [")", "", "select", "    group_type,", "    group_value,", "    fiscal_year_label,"]
    for row in public:
        name = row["kpi_name"]
        if row["metric_type"] in STATISTICS:
            gate = row["companies_metric"]
            lines.append(f"    case when {gate} >= {MIN_COMPANIES} then {name} end as {name},")
        else:
            lines.append(f"    {name},")
    always = sorted(
        {
            row["companies_metric"]
            for row in public
            if row["metric_type"] in STATISTICS and row["source_model"] != NEEDS_LATER_FILING
        }
    )
    later = sorted(
        {
            row["companies_metric"]
            for row in public
            if row["metric_type"] in STATISTICS and row["source_model"] == NEEDS_LATER_FILING
        }
    )
    small = [f"least({', '.join(always)}) < {MIN_COMPANIES}"]
    small += [f"(has_later_filing and {gate} < {MIN_COMPANIES})" for gate in later]
    lines += [
        "    nullif(",
        "        concat_ws(",
        "            '|',",
        "            case",
        "                when",
        "                    " + "\n                    or ".join(small),
        f"                    then '{FEWER_THAN_MIN}'",
        "            end,",
        f"            case when not has_later_filing then '{NOT_YET_OBSERVABLE}' end",
        "        ),",
        "        ''",
        "    ) as suppressed_reason",
        "from joined",
        "",
    ]
    return "\n".join(lines)


def public_model_yaml(rows: list[dict[str, str]]) -> dict:
    """Documentation and tests of rpt_public_group_metrics."""
    columns: list[dict] = [
        {
            "name": "group_type",
            "description": "Kind of group: " + ", ".join(GROUP_TYPES) + ".",
            "data_tests": [
                "not_null",
                {"accepted_values": {"arguments": {"values": list(GROUP_TYPES)}}},
            ],
        },
        {
            "name": "group_value",
            "description": "The group, e.g. Asset-heavy; 'All companies' for group_type all.",
            "data_tests": ["not_null"],
        },
        {
            "name": "fiscal_year_label",
            "description": "Financial year, e.g. FY2025-26.",
            "data_tests": ["not_null"],
        },
    ]
    for row in public_rows(rows):
        description = f"{row['label']}: {row['formula_text']}."
        if row["metric_type"] in STATISTICS:
            description += f" Empty when {row['companies_metric']} is below {MIN_COMPANIES}" + (
                " or the year has no later filing yet."
                if row["source_model"] == NEEDS_LATER_FILING
                else "."
            )
        elif row["source_model"] == NEEDS_LATER_FILING:
            description += " Empty (not 0) when the year has no later filing yet."
        columns.append({"name": row["kpi_name"], "description": description})
    reasons = [FEWER_THAN_MIN, NOT_YET_OBSERVABLE, f"{FEWER_THAN_MIN}|{NOT_YET_OBSERVABLE}"]
    columns.append(
        {
            "name": "suppressed_reason",
            "description": (
                f"Why some figures of the row are empty: {FEWER_THAN_MIN} (a statistic whose "
                f"companies count is below {MIN_COMPANIES}), {NOT_YET_OBSERVABLE} (restatement "
                "figures of a year with no later filing), or both joined by a bar. Empty when "
                "nothing is withheld."
            ),
            "data_tests": [
                {
                    "accepted_values": {
                        "arguments": {"values": reasons},
                        "config": {"where": "suppressed_reason is not null"},
                    }
                }
            ],
        }
    )
    return {
        "name": PUBLIC_MODEL,
        "description": (
            "PUBLIC model (docs/publication_policy.md): the group figures of the semantic layer "
            "by group type, group and financial year, generated from the same definitions as the "
            f"MetricFlow metrics. A statistic is empty when fewer than {MIN_COMPANIES} companies "
            "stand behind it; counts are always shown; no sum of filed values is a column. "
            "Public tools (Streamlit, AI analyst, public Power BI) read this table, never the "
            "semantic layer."
        ),
        "data_tests": [
            {
                "dbt_utils.unique_combination_of_columns": {
                    "arguments": {
                        "combination_of_columns": ["group_type", "group_value", "fiscal_year_label"]
                    }
                }
            }
        ],
        "columns": columns,
    }


