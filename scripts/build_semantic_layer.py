"""Generate the semantic layer (dbt + MetricFlow) from the KPI catalogue seed.

    python scripts/build_semantic_layer.py           # rewrite the YAML and the doc tables
    python scripts/build_semantic_layer.py --check   # exit 1 if either is out of date (pytest, CI)

dbt/seeds/kpi_catalogue.csv is the single source of truth. Every row whose metric_type is not
"company_value" becomes one MetricFlow metric:

    ratio_of_sums   sum(numerator) / sum(denominator) over the rows that have both (x 100 for %)
    median          median (percentile 0.5) of the numerator column
    average         average of the numerator column (never allowed for an intensity)
    share           rows where numerator holds / rows where denominator holds, x 100
    count           rows where the numerator condition holds
    count_distinct  distinct companies (with a value in the numerator column, if one is given)

Outputs: dbt/models/semantic/_semantic_layer.yml (whole file) and the two generated tables of
docs/semantic_layer.md. The entities and dimensions of the semantic models are fixed below; the
saved queries are written by hand in dbt/models/semantic/_saved_queries.yml.
The YAML uses the semantic-layer spec of dbt 1.12: the semantic model sits under its dbt model,
entities and dimensions under the columns, and simple metrics replace measures.
"""

