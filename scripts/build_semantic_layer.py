def _dimension(name: str, description: str) -> dict:
    return {"name": name, "description": description, "dimension": {"type": "categorical"}}


def _entity(
    column: str, entity: str, kind: str, description: str, tests: list | None = None
) -> dict:
    out = {"name": column, "description": description, "entity": {"name": entity, "type": kind}}
    if tests:
        out["data_tests"] = tests
    return out


