class CatalogueError(SystemExit):
    """A catalogue row breaks a rule of the semantic layer."""


def read_catalogue(seed: Path = SEED) -> list[dict[str, str]]:
    with seed.open(encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


def metric_rows(rows: list[dict[str, str]]) -> list[dict[str, str]]:
    # public_position rows are columns of two public company-level models, not group metrics
    return [row for row in rows if row["metric_type"] not in (COMPANY_VALUE, "public_position")]


def check_rules(rows: list[dict[str, str]]) -> None:
    """Refuse catalogue rows that would give a wrong or unpublishable metric."""
    by_name = {row["kpi_name"]: row for row in rows}
    problems: list[str] = []
    for row in metric_rows(rows):
        name, kind = row["kpi_name"], row["metric_type"]
        public = row["public_safe"] == "true"
        if kind not in METRIC_TYPES:
            problems.append(f"{name}: unknown metric_type {kind!r}")
            continue
        if row["source_model"] not in MODELS:
            problems.append(f"{name}: no semantic model for {row['source_model']}")
        if kind == "average" and row["unit_type"] in ("intensity", "pct"):
            problems.append(
                f"{name}: an average of company intensities or percentages is not a group "
                "figure; use ratio_of_sums (_agg) or median (_median)"
            )
        if kind == "ratio_of_sums" and not name.endswith("_agg"):
            problems.append(f"{name}: a ratio_of_sums metric must be named ..._agg")
        if kind == "median" and not name.endswith("_median"):
            problems.append(f"{name}: a median metric must be named ..._median")
        if kind in ("ratio_of_sums", "share") and not (row["numerator"] and row["denominator"]):
            problems.append(f"{name}: {kind} needs a numerator and a denominator")
        if kind in ("median", "average", "count") and not row["numerator"]:
            problems.append(f"{name}: {kind} needs a numerator")
        if kind in ("median", "average") and public:
            column = by_name.get(row["numerator"])
            if (
                column is None
                or column["metric_type"] != COMPANY_VALUE
                or column["source_model"] != row["source_model"]
                or column["public_safe"] != "true"
            ):
                problems.append(
                    f"{name}: a public {kind} must be taken over a public_safe column of "
                    f"{row['source_model']} (got {row['numerator']!r})"
                )
        if kind in STATISTICS and public and not row["companies_metric"]:
            problems.append(
                f"{name}: a public group statistic needs a companies_metric "
                f"(shown only for {MIN_COMPANIES} companies or more)"
            )
        if kind not in STATISTICS and row["companies_metric"]:
            problems.append(f"{name}: a plain count is always shown; remove companies_metric")
        gate = row["companies_metric"]
        if gate:
            gate_row = by_name.get(gate)
            if gate_row is None or gate_row["metric_type"] != "count_distinct":
                problems.append(f"{name}: companies_metric {gate!r} is not a count_distinct metric")
            elif gate_row["source_model"] != row["source_model"]:
                problems.append(f"{name}: companies_metric {gate!r} is on another table")
    if problems:
        raise CatalogueError("kpi_catalogue.csv:\n  " + "\n  ".join(problems))


def _meta(row: dict[str, str]) -> dict:
    meta: dict = {
        "public_safe": row["public_safe"] == "true",
        "metric_type": row["metric_type"],
        "unit": row["unit"],
        "direction": row["direction"],
    }
    if row["companies_metric"]:
        meta["min_companies"] = MIN_COMPANIES
        meta["companies_metric"] = row["companies_metric"]
    return meta


def _hidden_input(name: str, expr: str, what: str) -> dict:
    """A building block of a ratio: a sum of filed values, never public, hidden from tools."""
    return {
        "name": name,
        "type": "simple",
        "description": f"Building block ({what}); not a metric to read on its own.",
        "hidden": True,
        "agg": "sum",
        "expr": expr,
        "config": {"meta": {"public_safe": False, "metric_type": "input"}},
    }


def build_metrics(row: dict[str, str]) -> list[dict]:
    """The MetricFlow metric(s) of one catalogue row: hidden inputs first, then the metric."""
    name, kind = row["kpi_name"], row["metric_type"]
    num, den = row["numerator"], row["denominator"]
    head = {"name": name, "label": row["label"], "description": row["definition_plain"]}
    config = {"config": {"meta": _meta(row)}}

    if kind == "ratio_of_sums":
        # numerator and denominator over the same companies: those that have both
        both = f"{num} is not null and {den} <> 0"
        scale = "100.0 * " if row["unit_type"] == "pct" else ""
        return [
            _hidden_input(f"{name}_num", f"case when {both} then {scale}{num} end", "numerator"),
            _hidden_input(f"{name}_den", f"case when {both} then {den} end", "denominator"),
            {
                **head,
                "type": "ratio",
                "numerator": f"{name}_num",
                "denominator": f"{name}_den",
                **config,
            },
        ]
    if kind == "share":
        return [
            _hidden_input(
                f"{name}_num",
                f"case when ({num}) and ({den}) then 100.0 else 0 end",
                "rows counted, x 100",
            ),
            _hidden_input(f"{name}_den", f"case when {den} then 1 else 0 end", "rows in scope"),
            {
                **head,
                "type": "ratio",
                "numerator": f"{name}_num",
                "denominator": f"{name}_den",
                **config,
            },
        ]
    if kind == "median":
        return [
            {**head, "type": "simple", "agg": "percentile", "percentile": 0.5, "expr": num} | config
        ]
    if kind == "average":
        return [{**head, "type": "simple", "agg": "average", "expr": num} | config]
    if kind == "count":
        expr = f"case when {num} then 1 else 0 end"
        return [{**head, "type": "simple", "agg": "sum", "expr": expr} | config]
    if kind == "count_distinct":
        expr = f"case when {num} is not null then isin end" if num else "isin"
        return [{**head, "type": "simple", "agg": "count_distinct", "expr": expr} | config]
    raise CatalogueError(f"{name}: unknown metric_type {kind!r}")


def build_yaml(rows: list[dict[str, str]]) -> str:
    check_rules(rows)
    models = []
    for source, spec in MODELS.items():
        model: dict = {
            "name": spec["view"],
            "description": spec["description"],
            "semantic_model": True,
            "agg_time_dimension": TIME_DIMENSION,
        }
        if "primary_entity" in spec:
            model["primary_entity"] = spec["primary_entity"]
        model["columns"] = spec["columns"]
        model["metrics"] = [
            metric
            for row in metric_rows(rows)
            if row["source_model"] == source
            for metric in build_metrics(row)
        ]
        models.append(model)
    document = {"version": 2, "models": [*models, *EXTRA_MODELS, public_model_yaml(rows)]}

    class _NoAliases(yaml.SafeDumper):
        def ignore_aliases(self, data):  # the time column is shared by three models
            return True

    body = yaml.dump(document, Dumper=_NoAliases, sort_keys=False, width=1000, allow_unicode=True)
    return HEADER + body


